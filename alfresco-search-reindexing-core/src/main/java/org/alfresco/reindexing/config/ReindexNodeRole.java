package org.alfresco.reindexing.config;

/**
 * What this process is responsible for during a reindex, so shared wiring can adapt without knowing how the deployment is arranged.
 */
public interface ReindexNodeRole
{
    /** Whether this process reports job start and completion metrics. Only the process owning the job lifecycle should. */
    boolean recordsJobMetrics();

    /** Whether the ID range is handed over at runtime rather than read from {@code alfresco.reindex.fromId}/{@code toId}. When {@code true}, local range validation is skipped. */
    boolean rangeManagedExternally();
}
