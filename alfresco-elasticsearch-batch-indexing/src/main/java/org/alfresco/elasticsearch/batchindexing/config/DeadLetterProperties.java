package org.alfresco.elasticsearch.batchindexing.config;

import lombok.Getter;
import lombok.Setter;
import lombok.ToString;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.context.annotation.Configuration;

/**
 * Configuration properties for the dead-letter queue that records poison nodes the indexer has given up on.
 */
@Getter
@Setter
@ToString
@Configuration
@ConfigurationProperties(prefix = "alfresco.reindex.dead-letter")
public class DeadLetterProperties
{
    /** Operator kill-switch. When false, no DLQ index is created and no skip events are recorded. */
    private boolean enabled = true;

    /** Name of the Elasticsearch index that stores dead-letter records. */
    private String indexName = "alfresco-reindex-dead-letter";
}
